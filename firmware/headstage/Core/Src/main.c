/**
 * @brief  Retarget printf → USART1 (115 200 8N1).
 *
 * syscalls.c defines _write() which calls __io_putchar() per character.
 * The default __io_putchar is a weak no-op, so APP_DBG_MSG / printf output
 * was silently dropped.  This strong definition routes every character to
 * USART1 via blocking HAL_UART_Transmit (safe in task context; never called
 * from ISR because APP_DBG_MSG is only used in cooperative-scheduler tasks).
 */
int __io_putchar(int ch)
{
  HAL_UART_Transmit(&huart1, (uint8_t *)&ch, 1, HAL_MAX_DELAY);
  return ch;
}

