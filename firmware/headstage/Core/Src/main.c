/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
#ifdef DEBUG
  /* STM32WB0x: keep SWD/debugger alive during DEEPSTOP so CubeIDE can
     connect and program without holding the physical reset button.
     - PWR_DBGR.DEEPSTOP2 (bit 0): preserves the debug subsystem across deep-sleep.
     - HAL_PWREx_EnableDBGRetention(): retains the SWD GPIO pins on wake-up. */
  SET_BIT(PWR->DBGR, PWR_DBGR_DEEPSTOP2);
  HAL_PWREx_EnableDBGRetention();
#endif /* DEBUG */
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* Configure the peripherals common clocks */
  PeriphCommonClock_Config();

  /* USER CODE BEGIN SysInit */

  /* Output HSE (32 MHz, undivided) on PB14/MCO3 to clock the FPGA directly.
   * Tried sourcing SYSCLK/2 instead (also 32 MHz, but collapses the two
   * independent HSE->RC64MPLL and HSE->mypll PLL chains into one: SYSCLK is
   * itself HSE->RC64MPLL, and MCO's divider is a pure digital counter, no
   * PLL, so FPGA clk becomes a single HSE->RC64MPLL->SYSCLK->mypll chain
   * instead of two uncorrelated siblings). Result was inconclusive — the
   * only baseline available for comparison (vega_20260729_030823.csv) was
   * an 11.6 s / 12-event sample, too short at this ~1/s event rate to
   * distinguish from noise against the 60 s SYSCLK-sourced result
   * (vega_20260729_033443.csv, 1.37/s). Reverted to HSE-sourced to collect
   * a matched-duration (60 s) baseline for a fair head-to-head before
   * deciding which is actually better. */
  HAL_RCC_MCOConfig(RCC_MCO3, RCC_MCO1SOURCE_HSE, RCC_MCODIV_1);

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_RNG_Init();
  MX_RADIO_Init();
  MX_RADIO_TIMER_Init();
  MX_PKA_Init();
  MX_USART1_UART_Init();
  MX_RTC_Init();
  /* USER CODE BEGIN 2 */
  /* 5 s window to attach the ST-LINK debugger before BLE stack starts. */
  HAL_Delay(5000);

  /* Direct UART smoke-test — bypasses printf/syscalls entirely.
   * If this appears correctly in PuTTY at 115200, the UART HW and VCP are fine.
   * If it appears garbled, the baud rate in PuTTY is wrong — try 921600 / 57600.
   * If nothing appears, the VCP is not wired to PA1 (USART1 TX).               */
  {
    const char banner[] = "\r\n*** KUNTUR UART OK — 115200 8N1 ***\r\n";
    HAL_UART_Transmit(&huart1, (uint8_t *)banner, sizeof(banner) - 1U, 1000U);
  }
  /* USER CODE END 2 */

  /* Init code for STM32_BLE */
  MX_APPE_Init(NULL);

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */
    MX_APPE_Process();

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

